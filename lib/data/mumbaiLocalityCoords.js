/**
 * Case-insensitive lookup for locality coordinates.
 */
export function getCoordinatesForLocality(localityName) {
    if (!localityName || typeof localityName !== 'string') return null;
    const clean = localityName.trim().toLowerCase();
    
    // Exact match
    for (const [name, coords] of Object.entries(MUMBAI_LOCALITY_COORDS)) {
        if (name.toLowerCase() === clean) return coords;
    }
    
    // Partial match (e.g. "Kharghar" matching "Navi Mumbai (Kharghar)")
    for (const [name, coords] of Object.entries(MUMBAI_LOCALITY_COORDS)) {
        const nameLower = name.toLowerCase();
        if (nameLower.includes(clean) || clean.includes(nameLower)) {
            return coords;
        }
    }
    
    return null;
}
